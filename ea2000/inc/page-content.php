/**
 * แปลงข้อความจาก textarea เป็น HTML ที่ escape แล้ว
 */
function ea2000_rich_text( $text ) {
	$text   = str_replace( array( "\r\n", "\r" ), "\n", (string) $text );
	$blocks = preg_split( '/\n\s*\n/', trim( $text ) );
	$html   = '';

	foreach ( $blocks as $block ) {
		$lines = array_values( array_filter( array_map( 'trim', explode( "\n", $block ) ), 'strlen' ) );
		if ( empty( $lines ) ) {
			continue;
		}

		$is_table = count( $lines ) > 1;
		foreach ( $lines as $line ) {
			if ( false === strpos( $line, ' | ' ) ) {
				$is_table = false;
				break;
			}
		}

		if ( $is_table ) {
			$html .= '<div class="doc-table-wrap"><table class="doc-table">';
			foreach ( $lines as $idx => $line ) {
				$cells = array_map( 'trim', explode( ' | ', $line ) );
				$tag   = 0 === $idx ? 'th' : 'td';
				$html .= 0 === $idx ? '<thead><tr>' : ( 1 === $idx ? '<tbody><tr>' : '<tr>' );
				foreach ( $cells as $cell ) {
					$html .= '<' . $tag . '>' . esc_html( $cell ) . '</' . $tag . '>';
				}
				$html .= '</tr>' . ( 0 === $idx ? '</thead>' : '' );
			}
			$html .= '</tbody></table></div>';
			continue;
		}

		$first = $lines[0];

		if ( 0 === strpos( $first, '### ' ) ) {
			$html .= '<h3>' . esc_html( substr( $first, 4 ) ) . '</h3>';
			$rest  = array_slice( $lines, 1 );
			if ( ! empty( $rest ) ) {
				$html .= '<p>' . implode( '<br>', array_map( 'esc_html', $rest ) ) . '</p>';
			}
			continue;
		}

		if ( 0 === strpos( $first, '- ' ) ) {
			$html .= '<ul>';
			foreach ( $lines as $line ) {
				$html .= '<li>' . esc_html( preg_replace( '/^-\s+/', '', $line ) ) . '</li>';
			}
			$html .= '</ul>';
			continue;
		}

		if ( preg_match( '/^\d+\.\s/', $first ) ) {
			$html .= '<ol>';
			foreach ( $lines as $line ) {
				$html .= '<li>' . esc_html( preg_replace( '/^\d+\.\s+/', '', $line ) ) . '</li>';
			}
			$html .= '</ol>';
			continue;
		}

		$html .= '<p>' . implode( '<br>', array_map( 'esc_html', $lines ) ) . '</p>';
	}

	return $html;
}

/**
 * พิมพ์หัวข้อเนื้อหาของหน้าย่อย ({prefix}_secN_title / {prefix}_secN_text)
 */
function ea2000_page_sections( $prefix, $max = 10, $wrap = true ) {
	$items = array();
	for ( $i = 1; $i <= $max; $i++ ) {
		$title = trim( (string) ea2000_mod( $prefix . '_sec' . $i . '_title' ) );
		$text  = trim( (string) ea2000_mod( $prefix . '_sec' . $i . '_text' ) );
		if ( '' === $title && '' === $text ) {
			continue;
		}
		if ( ea2000_is_placeholder( $title ) || ea2000_is_placeholder( $text ) ) {
			continue;
		}
		$items[] = array( $i, $title, $text );
	}
	if ( empty( $items ) ) {
		return;
	}
	if ( $wrap ) {
		echo '<section class="section doc-sections" id="' . esc_attr( $prefix . '-doc' ) . '"><div class="container-narrow"><div class="entry-content doc-body">';
	}
	foreach ( $items as $item ) {
		echo '<article class="doc-section reveal" id="' . esc_attr( $prefix . '-sec-' . $item[0] ) . '">';
		if ( '' !== $item[1] ) {
			echo '<h2>' . esc_html( $item[1] ) . '</h2>';
		}
		echo ea2000_rich_text( $item[2] ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped inside ea2000_rich_text
		echo '</article>';
	}
	if ( $wrap ) {
		echo '</div></div></section>';
	}
}

/**
 * ฟิลด์ Customizer สำหรับหัวข้อเนื้อหาของหน้าย่อย
 */
function ea2000_page_section_fields( $prefix, $max = 10 ) {
	$fields = array();
	$rule   = 'รูปแบบ: เว้นบรรทัดว่าง = ย่อหน้าใหม่ · "- " = รายการ · "1. " = ลำดับ · "### " = หัวข้อย่อย · " | " = ตาราง · ห้ามระบุกลยุทธ์ ตัวเลขผลเทรด หรือคำรับประกัน';
	for ( $i = 1; $i <= $max; $i++ ) {
		$fields[ $prefix . '_sec' . $i . '_title' ] = array( 'หัวข้อที่ ' . $i, 'text' );
		$fields[ $prefix . '_sec' . $i . '_text' ]  = array( 'เนื้อหาหัวข้อที่ ' . $i, 'textarea', $rule );
	}
	return $fields;
}

