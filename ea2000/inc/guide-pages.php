/**
 * ฟิลด์ Customizer ของหน้าคู่มือหนึ่งหน้า
 *
 * @param string $prefix prefix ของชุดข้อมูล
 * @return array<string,array>
 */
function ea2000_guide_fields( $prefix ) {
	$rule   = 'ห้ามระบุกลยุทธ์ ตัวเลขผลเทรด หรือคำรับประกัน';
	$fields = array(
		$prefix . '_kicker'      => array( 'ป้ายเหนือชื่อหน้า', 'text' ),
		$prefix . '_sub'         => array( 'คำโปรยใต้ชื่อหน้า', 'textarea' ),
		$prefix . '_intro'       => array( 'ย่อหน้าเกริ่นนำ', 'textarea', $rule ),
		$prefix . '_quick_title' => array( 'หัวข้อกล่องภาพรวม', 'text' ),
		$prefix . '_quick'       => array( 'ภาพรวมขั้นตอนแบบย่อ', 'textarea' ),
	);

	for ( $i = 1; $i <= ea2000_guide_step_count(); $i++ ) {
		$fields[ $prefix . '_step' . $i . '_title' ]    = array( 'ขั้นที่ ' . $i . ' · หัวข้อ', 'text' );
		$fields[ $prefix . '_step' . $i . '_desc' ]     = array( 'ขั้นที่ ' . $i . ' · คำอธิบาย', 'textarea', $rule );
		$fields[ $prefix . '_step' . $i . '_img' ]      = array( 'ขั้นที่ ' . $i . ' · ภาพประกอบ', 'image' );
		$fields[ $prefix . '_step' . $i . '_img_alt' ]  = array( 'ขั้นที่ ' . $i . ' · ข้อความแทนภาพ (Alt)', 'text' );
		$fields[ $prefix . '_step' . $i . '_img_note' ] = array( 'ขั้นที่ ' . $i . ' · ข้อความในช่องรอรูป', 'text' );
	}

	$fields[ $prefix . '_check_title' ] = array( 'หัวข้อกล่องเช็กลิสต์', 'text' );
	$fields[ $prefix . '_check' ]       = array( 'รายการเช็กลิสต์ (บรรทัดละ 1 ข้อ)', 'textarea', $rule );

	for ( $s = 1; $s <= 4; $s++ ) {
		$fields[ $prefix . '_sec' . $s . '_title' ] = array( 'หัวข้อเสริมที่ ' . $s, 'text' );
		$fields[ $prefix . '_sec' . $s . '_text' ]  = array(
			'เนื้อหาหัวข้อเสริมที่ ' . $s,
			'textarea',
			'รูปแบบ: เว้นบรรทัดว่าง = ย่อหน้าใหม่ · "- " = รายการ · "1. " = ลำดับ · "### " = หัวข้อย่อย · " | " = ตาราง · ' . $rule,
		);
	}

	return $fields;
}
