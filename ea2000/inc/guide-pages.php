/**
 * แผนที่ slug ของเพจ ไปยัง prefix ของชุดข้อมูล
 *
 * @return array<string,string>
 */
function ea2000_guide_map() {
	return apply_filters(
		'ea2000_guide_map',
		array(
			'vps-windows'      => 'gvwin',
			'vps-android'      => 'gvand',
			'vps-ios'          => 'gvios',
			'mt5-login'        => 'gmt5',
			'open-mt5-account' => 'gacct',
		)
	);
}

/**
 * prefix ของหน้าคู่มือที่กำลังแสดงอยู่ ('' = ไม่ใช่หน้าคู่มือ)
 *
 * @param int $post_id id ของเพจ (0 = ใช้เพจปัจจุบัน)
 * @return string
 */
function ea2000_guide_prefix( $post_id = 0 ) {
	$post_id = $post_id ? (int) $post_id : (int) get_queried_object_id();
	if ( ! $post_id ) {
		return '';
	}

	$slug = get_post_field( 'post_name', $post_id );
	$map  = ea2000_guide_map();

	return isset( $map[ $slug ] ) ? $map[ $slug ] : '';
}

