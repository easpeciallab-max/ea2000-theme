	$fields[ $prefix . '_check' ]       = array( 'รายการเช็กลิสต์ (บรรทัดละ 1 ข้อ)', 'textarea', $rule );

	for ( $s = 1; $s <= 4; $s++ ) {
		$fields[ $prefix . '_sec' . $s . '_title' ] = array( 'หัวข้อเสริมที่ ' . $s, 'text' );
